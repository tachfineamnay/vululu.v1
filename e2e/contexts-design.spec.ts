import { test, expect } from '@playwright/test';

test('marques et références : création, erreur conservée, recherche, révision, ressources et retour au projet', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(process.env.DEMO_EMAIL ?? '');
  await page.getByLabel('Mot de passe', { exact: true }).fill(process.env.DEMO_PASSWORD ?? '');
  await page.getByRole('button', { name: 'Entrer dans le studio' }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto('/contexts/new');
  await expect(page.getByTestId('context-name')).toHaveValue('');
  await expect(page.getByTestId('context-description')).toHaveValue('');
  await expect(page.getByTestId('context-website')).not.toBeVisible();
  await page.getByTestId('context-submit').click();
  expect(await page.getByTestId('context-name').evaluate((el: HTMLInputElement) => el.validity.valueMissing)).toBe(true);
  const name = 'Univers éditorial ' + Date.now();
  await page.getByTestId('context-name').fill(name);
  await page.getByTestId('context-description').fill('Des récits et des images. Contrainte : aucun visage identifiable.');
  page.once('dialog', (dialog) => dialog.dismiss());
  await page.getByRole('link', { name: 'Retour aux contextes', exact: true }).click();
  await expect(page).toHaveURL(/\/contexts\/new$/);
  await expect(page.getByTestId('context-name')).toHaveValue(name);
  // Échec réseau contrôlé, annoncé comme tel ; aucune capacité métier simulée.
  await page.route('**/api/contexts', async (route) => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, json: { message: 'Échec réseau contrôlé de recette' } }) : route.continue());
  await page.getByTestId('context-submit').click();
  await expect(page.getByTestId('context-error')).toContainText('Échec réseau contrôlé');
  await expect(page.getByTestId('context-name')).toHaveValue(name);
  await page.unroute('**/api/contexts');
  await page.getByTestId('context-submit').click();
  await expect(page).toHaveURL(/\/contexts\?context=/);
  const contextId = new URL(page.url()).searchParams.get('context')!;
  await expect(page.getByTestId('context-detail')).toContainText(name);
  await expect(page.getByTestId('context-detail').getByText('À compléter si utile : site de référence, public, ton. Les références restent facultatives.')).toBeVisible();
  await expect(page.getByTestId('context-name')).toHaveCount(0);
  await page.getByLabel('Retrouver un contexte').fill('ÉDITORIAL');
  await expect(page.getByTestId('contexts-list')).toContainText(name);
  await page.getByLabel('Retrouver un contexte').fill('aucun-résultat-xyz');
  await expect(page.getByText('Aucun contexte ne correspond à cette recherche.')).toBeVisible();
  await page.getByRole('button', { name: 'Effacer la recherche' }).click();
  await page.getByRole('button', { name: 'Modifier la fiche', exact: true }).click();
  await expect(page.getByTestId('context-name')).toBeFocused();
  await page.getByTestId('context-description').fill('Univers éditorial modifié manuellement. Aucun visage identifiable.');
  await page.getByText('Préciser le public et le ton (facultatif)', { exact: true }).click();
  await page.getByTestId('context-tone').fill('Direct et documentaire');
  await page.getByText('Références et couleurs (facultatif)', { exact: true }).click();
  await page.getByTestId('context-website').fill('https://example.com/reference-non-analysee');
  const save = page.getByRole('button', { name: 'Confirmer et enregistrer la fiche', exact: true });
  await expect(save).toBeDisabled();
  await page.getByRole('checkbox', { name: 'J’ai relu les informations et les hypothèses ; je confirme cette fiche.' }).check();
  await save.click();
  await expect(page.locator('.toast--success')).toContainText('révision 2');
  await page.reload();
  await expect(page.getByTestId('context-detail')).toContainText('Univers éditorial modifié manuellement.');
  await expect(page.getByTestId('context-detail')).toContainText('non consultée et non analysée');
  await expect(page.getByRole('region', { name: 'Historique du contexte' }).locator('details')).toHaveCount(2);
  // Un concurrent crée une vraie révision : la saisie locale ne doit pas être écrasée.
  const source = await (await page.request.get(`/api/contexts/${contextId}/review`)).json();
  const csrf = await page.evaluate(() => decodeURIComponent(document.cookie.split('; ').find((part) => part.startsWith('vululu_csrf='))?.split('=')[1] ?? ''));
  await page.getByRole('button', { name: 'Modifier la fiche', exact: true }).click();
  await page.getByTestId('context-description').fill('Brouillon local conservé après un conflit de révision.');
  const concurrent = await page.request.put(`/api/contexts/${contextId}/review`, { headers: { 'x-csrf-token': csrf }, data: { content: { ...source.revisions.at(-1).snapshot, tone: 'Ton confirmé dans une autre session' }, expectedVersion: source.version, confirmed: true } });
  expect(concurrent.status()).toBe(200);
  await page.getByRole('checkbox', { name: 'J’ai relu les informations et les hypothèses ; je confirme cette fiche.' }).check();
  await page.getByRole('button', { name: 'Confirmer et enregistrer la fiche', exact: true }).click();
  await expect(page.getByTestId('context-detail').getByRole('alert')).toBeVisible();
  await expect(page.getByTestId('context-description')).toHaveValue('Brouillon local conservé après un conflit de révision.');
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Annuler les modifications' }).click();
  await page.reload();
  await expect(page.getByTestId('context-detail')).toContainText('Ton confirmé dans une autre session');
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `débordement à ${width}px`).toBe(true);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('link', { name: 'Créer un projet avec ce contexte' }).click();
  await page.getByTestId('project-title').fill('Projet de recette du contexte');
  await page.getByTestId('project-objective').fill('Faire connaître cet univers éditorial.');
  await page.getByTestId('project-next').click();
  await expect(page.getByTestId('project-context')).toHaveValue(contextId);
  await page.getByTestId('project-next').click();
  await page.getByTestId('project-next').click();
  await page.getByTestId('project-submit').click();
  await expect(page.getByTestId('project-title-heading')).toHaveText('Projet de recette du contexte');
  const projectUrl = page.url();
  await page.getByRole('link', { name: 'Contexte : ' + name, exact: true }).click();
  await expect(page.getByTestId('context-detail')).toContainText(name);
  await page.getByRole('link', { name: 'Gérer les ressources de ce contexte' }).click();
  await expect(page.getByLabel('Contexte', { exact: true })).toHaveValue(contextId);
  await page.getByText('Ajouter un fichier ou une version', { exact: true }).click();
  await page.getByLabel('Type d’actif').selectOption('document');
  await page.getByLabel('Nom de la version').fill('Références éditoriales');
  await page.getByLabel('Fichier', { exact: true }).setInputFiles({ name: 'references.txt', mimeType: 'text/plain', buffer: Buffer.from('Référence fictive de recette. Droits déclarés par le test.') });
  await page.getByLabel('Provenance et autorisation').fill('Document original fictif pour la recette locale.');
  await page.getByRole('button', { name: 'Importer et vérifier', exact: true }).click();
  await expect(page.locator('.toast--success')).toContainText('Version 1 importée et vérifiée');
  const projectId = projectUrl.split('/').pop()!;
  await page.getByLabel('Sélection pour un projet').selectOption(projectId);
  await expect(page.getByLabel('Utiliser la version 1')).toBeDisabled();
  await expect(page.getByText('Droits à confirmer : cette version ne peut pas être sélectionnée pour un projet.', { exact: false })).toBeVisible();
  await page.getByRole('link', { name: 'Retour au projet', exact: true }).click();
  await expect(page).toHaveURL(projectUrl);
  await page.getByRole('link', { name: 'Ressources du projet', exact: true }).click();
  await expect(page.getByLabel('Sélection pour un projet')).toHaveValue(projectId);
  await expect(page.getByLabel('Contexte', { exact: true })).toHaveValue(contextId);
});

test('fondations : clavier, cascade et bannière conservés après navigation', async ({ page }) => {
  await page.goto('/contexts/new');
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'Aller au contenu' })).toBeFocused();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Tab');
  await expect(page.getByTestId('context-name')).toBeFocused();
  const focus = await page.getByTestId('context-name').evaluate((el) => {
    const s = getComputedStyle(el); return { outline: s.outlineStyle, width: s.outlineWidth, color: s.outlineColor, height: el.getBoundingClientRect().height };
  });
  expect(focus).toMatchObject({ outline: 'solid', width: '2px', color: 'rgb(35, 71, 190)' });
  expect(focus.height).toBeGreaterThanOrEqual(48);
  await page.getByText('Références et couleurs (facultatif)', { exact: true }).press('Enter');
  await expect(page.getByTestId('context-website')).toBeVisible();
  await page.goto('/login');
  await expect(page.locator('[data-vululu-theme="blue"]')).toHaveCount(0);
  await expect(page.getByTestId('login-submit')).toHaveCSS('background-image', /linear-gradient/);
  await expect(page.getByRole('note', { name: 'Mode demonstration' })).toContainText('MODE DÉMO');
  await page.goto('/admin');
  await expect(page.locator('[data-vululu-theme="blue"]')).toHaveCount(0);
});

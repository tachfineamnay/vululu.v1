import { test, expect } from '@playwright/test';

test('Mes projets : idée, références, destination, sauvegarde et reprise du brief confirmé', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(process.env.DEMO_EMAIL ?? '');
  await page.getByLabel('Mot de passe', { exact: true }).fill(process.env.DEMO_PASSWORD ?? '');
  await page.getByTestId('login-submit').click(); await expect(page).toHaveURL(/\/$/);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Mes projets');
  await expect(page.getByTestId('new-project')).toHaveText('Nouveau projet');
  await page.getByTestId('new-project').click();
  const title = 'Projet guidé ' + Date.now();
  const idea = 'Présenter une activité créative et inviter à la découvrir.';
  await expect(page.getByTestId('project-title')).toHaveValue('');
  await page.getByTestId('project-next').click();
  await expect(page.getByTestId('project-title')).toBeFocused();
  await page.getByTestId('project-title').fill(title);
  await page.getByTestId('project-objective').fill(idea);
  await page.getByTestId('project-next').click();
  await expect(page.getByRole('heading', { name: 'Vos références', exact: true })).toBeFocused();
  // Création de contexte via le parcours réel, avec retour au brouillon du même onglet.
  await page.getByRole('link', { name: 'Créer un contexte et revenir ici' }).click();
  await page.getByTestId('context-name').fill('Univers du projet guidé');
  await page.getByTestId('context-description').fill('Un univers créatif fictif pour la recette du parcours.');
  await page.getByTestId('context-submit').click();
  await expect(page).toHaveURL(/\/projects\/new\?context=/);
  const contextId = new URL(page.url()).searchParams.get('context')!;
  await expect(page.getByTestId('project-context')).toHaveValue(contextId);
  await expect(page.getByTestId('project-draft-status')).toContainText('Brouillon repris');
  await page.getByRole('button', { name: 'Étape précédente' }).click();
  await expect(page.getByTestId('project-title')).toHaveValue(title);
  await expect(page.getByTestId('project-objective')).toHaveValue(idea);
  await page.getByTestId('project-next').click(); await page.getByTestId('project-next').click();
  await page.getByTestId('project-platform').selectOption('LinkedIn');
  await expect(page.getByText('Cadre carré', { exact: true })).toBeVisible();
  await expect(page.getByTestId('project-format').locator('option[value="Affiche"]')).toHaveJSProperty('disabled', true);
  await page.reload();
  await expect(page.getByTestId('project-platform')).toHaveValue('LinkedIn');
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `débordement à ${width}`).toBe(true);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByTestId('project-next').click();
  await expect(page.getByText('Cette action ne lance aucune génération.', { exact: false })).toBeVisible();
  await page.route('**/api/projects', async (route) => route.request().method() === 'POST' ? route.fulfill({ status: 503, json: { message: 'Échec contrôlé de création' } }) : route.continue());
  await page.getByTestId('project-submit').click();
  await expect(page.getByTestId('project-error')).toContainText('Échec contrôlé');
  await expect(page.getByRole('definition').filter({ hasText: title })).toBeVisible();
  await page.unroute('**/api/projects'); await page.getByTestId('project-submit').click();
  await expect(page.getByTestId('project-title-heading')).toHaveText(title);
  await expect(page.getByRole('heading', { name: 'Préparer et valider le brief', exact: true })).toBeFocused();
  const projectUrl = page.url(); const id = projectUrl.split('/').pop()!;
  await expect(page.getByTestId('brief-objective')).toHaveValue(idea);
  await expect(page.getByTestId('brief-confirm')).toHaveCount(0);
  await expect(page.getByTestId('storyboard-generate')).toBeDisabled();
  await page.getByTestId('brief-audience').fill('Public intéressé par cette activité');
  await page.getByTestId('brief-tone').fill('Clair et direct');
  await page.getByTestId('brief-cta').fill('Découvrir cette activité');
  page.once('dialog', (dialog) => dialog.dismiss());
  await page.getByTestId('nav-home').click();
  await expect(page).toHaveURL(projectUrl);
  await page.getByTestId('brief-save').click();
  await expect(page.getByTestId('toast')).toContainText('Brief enregistre');
  await expect(page.getByTestId('production-plan')).toContainText('Livrables prévus');
  await expect(page.getByTestId('plan-estimate')).toContainText('centimes MOCK');
  await expect(page.getByTestId('brief-confirm')).toContainText('et son plafond');
  await expect(page.getByTestId('brief-confirm')).toBeEnabled();
  await page.getByTestId('brief-confirm').click();
  await expect(page.getByTestId('toast')).toContainText('Version exacte du brief confirmée');
  await page.reload();
  await expect(page.getByTestId('brief-cta')).toHaveValue('Découvrir cette activité');
  await expect(page.getByTestId('brief-confirm')).toBeDisabled();
  await expect(page.getByTestId('storyboard-generate')).toBeEnabled();
  await page.getByTestId('nav-home').click();
  const summary = page.getByTestId('project-summary-' + id);
  await expect(summary).toContainText('Univers du projet guidé');
  await expect(summary).toContainText(idea);
  await expect(summary).toContainText('Brief enregistré');
  await expect(summary).toContainText('Relire le brief et son plan');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await summary.getByRole('link', { name: 'Reprendre ' + title, exact: true }).click();
  await expect(page).toHaveURL(projectUrl);
  await expect(page.getByTestId('brief-cta')).toHaveValue('Découvrir cette activité');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
});

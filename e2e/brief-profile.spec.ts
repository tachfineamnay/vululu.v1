import { test, expect } from '@playwright/test';

test('brief confirme : profil reel, revisions et storyboard perime', async ({ page }) => {
  expect(process.env.DEMO_EMAIL).toBeTruthy(); expect(process.env.DEMO_PASSWORD).toBeTruthy();
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(process.env.DEMO_EMAIL!);
  await page.getByLabel('Mot de passe', { exact: true }).fill(process.env.DEMO_PASSWORD!);
  await page.getByRole('button', { name: 'Entrer dans le studio' }).click();
  await expect(page).toHaveURL(/\/$/);
  const csrf = await page.evaluate(() => decodeURIComponent(document.cookie.split('; ').find((part) => part.startsWith('vululu_csrf='))?.split('=')[1] ?? ''));
  const headers = { 'x-csrf-token': csrf };
  const contextResponse = await page.request.post('/api/contexts', { headers, data: { name: 'Profil E2E ' + Date.now(), description: 'Marque fictive pour la recette du brief' } });
  expect(contextResponse.status()).toBe(201);
  const { context } = await contextResponse.json();
  const response = await page.request.post('/api/projects', { headers, data: { contextId: context.id, title: 'Profil 4:5 E2E', platform: 'Instagram', format: 'Video', objective: 'Recette fictive' } });
  expect(response.status()).toBe(201);
  const { project } = await response.json();
  await page.goto('/projects/' + project.id);
  await expect(page.getByTestId('storyboard-generate')).toBeDisabled();
  await page.getByTestId('brief-objective').fill('Présenter la marque fictive');
  await page.getByTestId('brief-audience').fill('Public de démonstration');
  await page.getByTestId('brief-tone').fill('Clair et direct');
  await page.getByTestId('brief-cta').fill('Découvrir la collection');
  await page.getByLabel('Ratio de sortie', { exact: true }).selectOption('4:5');
  await page.getByLabel('Style de simulation', { exact: true }).selectOption('bold');
  await page.getByLabel('Direction artistique simulée', { exact: true }).fill('Plan produit');
  await page.getByLabel('Durée par défaut d’une scène (secondes)').fill('1');
  await page.getByLabel('Plafond du run en centimes MOCK').fill('0');
  await page.getByTestId('brief-save').click();
  await expect(page.getByTestId('production-plan')).toContainText('Plan et estimation MOCK');
  await expect(page.getByTestId('plan-estimate')).toHaveText('Estimation indicative : 0 centimes MOCK. Plafond du brief : 0 centimes MOCK.');
  expect((await page.getByRole('button', { name: 'Recalculer le plan', exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await expect(page.getByTestId('brief-confirm')).toBeEnabled();
  await expect(page.getByTestId('storyboard-generate')).toBeDisabled();
  await page.getByTestId('brief-confirm').click();
  await expect(page.getByTestId('storyboard-generate')).toBeEnabled();
  await page.getByTestId('storyboard-generate').click();
  await expect(page.getByTestId('duration-summary')).toHaveText('5 scenes / 5 s');
  for (let i = 1; i <= 5; i++) await expect(page.getByTestId('duration-SCENE-00' + i)).toHaveValue('1');
  await expect(page.getByTestId('produce')).toBeEnabled();
  await page.getByTestId('duration-SCENE-003').selectOption('3');
  await expect(page.getByTestId('duration-origin-SCENE-003')).toContainText('personnalisée');
  const initialScenes = (await (await page.request.get('/api/projects/' + project.id)).json()).scenes;
  await page.getByTestId('brief-cta').fill('Découvrir la nouvelle collection');
  await page.getByLabel('Durée par défaut d’une scène (secondes)').fill('2');
  await expect(page.getByTestId('produce')).toBeDisabled();
  await expect(page.getByTestId('brief-confirm')).toBeDisabled();
  await page.getByTestId('brief-save').click();
  await expect(page.getByTestId('production-plan')).toContainText('5 scènes · 11 s');
  await expect(page.getByTestId('brief-confirm')).toBeEnabled();
  await page.getByTestId('brief-confirm').click();
  await expect(page.getByTestId('storyboard-generate')).toBeEnabled();
  await expect(page.getByTestId('produce')).toBeDisabled();
  await page.getByTestId('storyboard-generate').click();
  await expect(page.getByTestId('duration-summary')).toHaveText('5 scenes / 11 s');
  const regenerated = (await (await page.request.get('/api/projects/' + project.id)).json()).scenes;
  expect(regenerated.map((scene: { id: string }) => scene.id)).toEqual(initialScenes.map((scene: { id: string }) => scene.id));
  expect(regenerated.map((scene: { durationSeconds: number }) => scene.durationSeconds)).toEqual([2, 2, 3, 2, 2]);
  await page.setViewportSize({ width: 390, height: 844 });
  if (process.env.CAPTURE_STUDIO === '1') await page.getByTestId('duration-reset-SCENE-003').locator('..').screenshot({ path: '.v1/duration-mobile.png' });
  await page.getByTestId('duration-reset-SCENE-003').click();
  await expect(page.getByTestId('duration-origin-SCENE-003')).toContainText('Suit la durée du brief');
  await expect(page.getByTestId('duration-reset-SCENE-003')).toHaveCount(0);
  await expect(page.getByTestId('duration-summary')).toHaveText('5 scenes / 10 s');
  await expect(page.getByTestId('production-plan')).toContainText('5 scènes · 10 s');
  await page.reload();
  await expect(page.getByTestId('duration-origin-SCENE-003')).toContainText('Suit la durée du brief');
  await expect(page.getByTestId('produce')).toBeEnabled();
  await page.getByTestId('produce').click();
  await expect(page.getByTestId('status-badge')).toHaveText('Aperçu pret', { timeout: 180000 });
  const video = page.getByTestId('master-video');
  await expect.poll(() => video.evaluate((element) => (element as HTMLVideoElement).videoHeight)).toBe(1350);
  expect(await video.evaluate((element) => (element as HTMLVideoElement).videoWidth)).toBe(1080);
  expect(await video.evaluate((element) => (element as HTMLVideoElement).duration)).toBeCloseTo(10, 1);
  const bundle = await (await page.request.get('/api/projects/' + project.id)).json();
  expect(bundle.brief).toMatchObject({ version: 2, confirmedVersion: 2, settings: { ratio: '4:5', visualStyle: 'bold' } });
  expect(bundle.brief.revisions).toHaveLength(2);
  expect(bundle.master.qaStatus).toBe('PASS');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.CAPTURE_STUDIO === '1') await page.screenshot({ path: '.v1/brief-profile.png', fullPage: true });
});

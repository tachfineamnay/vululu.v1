CREATE TABLE "ConfirmedOffer" (
  id TEXT PRIMARY KEY, "contextId" TEXT NOT NULL REFERENCES "BrandContext" ON DELETE CASCADE ON UPDATE CASCADE,
  name TEXT NOT NULL, UNIQUE ("contextId", name)
);
CREATE TABLE "ContentItem" (
  id TEXT PRIMARY KEY, "userId" TEXT NOT NULL REFERENCES "User" ON DELETE CASCADE ON UPDATE CASCADE,
  "offerId" TEXT NOT NULL REFERENCES "ConfirmedOffer" ON DELETE RESTRICT ON UPDATE CASCADE,
  "campaignId" TEXT REFERENCES "Campaign" ON DELETE SET NULL ON UPDATE CASCADE,
  "projectId" TEXT REFERENCES "Project" ON DELETE SET NULL ON UPDATE CASCADE,
  title TEXT NOT NULL, audience TEXT NOT NULL, objective TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('IDEA','DRAFT','READY_FOR_REVIEW','APPROVED','SCHEDULED','PUBLISHED','FAILED')),
  "plannedAt" TIMESTAMPTZ(3) NOT NULL, "timeZone" TEXT NOT NULL, variants JSONB NOT NULL,
  archived BOOLEAN NOT NULL DEFAULT false, version INTEGER NOT NULL
);
CREATE INDEX "ContentItem_userId_plannedAt_idx" ON "ContentItem"("userId", "plannedAt");
CREATE TABLE "ContentRevision" (
  "itemId" TEXT NOT NULL REFERENCES "ContentItem" ON DELETE CASCADE ON UPDATE CASCADE,
  version INTEGER NOT NULL, "requestId" TEXT NOT NULL, digest TEXT NOT NULL, snapshot JSONB NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("itemId", version), UNIQUE ("itemId", "requestId")
);
